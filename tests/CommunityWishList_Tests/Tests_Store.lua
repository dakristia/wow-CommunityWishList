-- Store tests. Register with T.add(name, fn).
local T = CommunityWishList_Tests

local function wish(store, qty)
    return assert(store:AddWish({ name = "Herb", qty = qty or 10, guild = true }))
end

T.add("codec round trip and invalid input", function()
    local codec = CommunityWishList.Codec
    local value = { text = "a|b:c\n\0%00", nested = { -2.75, true, false }, n = 1 / 3 }
    local wire = assert(codec.Serialize(value))
    T.check(not wire:find("\0", 1, true))
    local decoded = codec.Deserialize(wire)
    T.eq(decoded.text, value.text)
    T.eq(decoded.n, value.n)
    T.eq(decoded.nested[1], -2.75)
    T.eq(decoded.nested[2], true)
    T.eq(decoded.nested[3], false)
    for _, input in ipairs({ "garbage", "s5:abc", "t1:s1:xt1:s1:xt1:s1:xt1:s1:xt1:s1:xt1:s1:xt1:s1:xt1:s1:xt0:" }) do
        local ok, result = pcall(codec.Deserialize, input)
        T.check(ok)
        T.eq(result, nil)
    end
end)

T.add("wish validation and ownership", function()
    local a = T.newStore("Ann-Realm", "Guild")
    local b = T.newStore("Bob-Realm", "Guild")
    T.eq(a:AddWish({ name = "Herb", qty = 0, guild = true }), nil)
    local w = assert(a:AddWish({ name = "Herb", qty = 10, guild = true, note = "hello\nworld" }))
    T.eq(w.id, "Ann-Realm:1")
    T.eq(w.owner, "Ann-Realm")
    T.eq(w.note, "helloworld")
    T.eq(w.prio, 2)
    T.eq(w.gold, 0)
    T.eq(a:Claim(w.id, 1), nil)
    b:Merge(w)
    T.eq(b:CloseWish(w.id), nil)
    T.eq(b:Claim(w.id, 11), nil)
    local c = assert(b:Claim(w.id, 4))
    T.eq(b:Remaining(b:Get(w.id)), 6)
    a:Merge(b:Get(w.id))
    T.eq(a:CancelClaim(w.id, c.id), nil)
    T.eq(a:ClaimedQty(a:Get(w.id)), 4)
end)

T.add("sent claims close only owner store", function()
    local a = T.newStore("Ann-Realm", "Guild")
    local b = T.newStore("Bob-Realm", "Guild")
    local w = wish(a, 3)
    b:Merge(w)
    local c = assert(b:Claim(w.id, 3))
    assert(b:MarkSent(w.id, c.id))
    T.eq(b:Get(w.id).state, "open")
    a:Merge(b:Get(w.id))
    T.eq(a:Get(w.id).state, "closed")
    T.eq(a:SentQty(a:Get(w.id)), 3)
end)

T.add("merge claims versions tombstones and digest", function()
    local a = T.newStore("Ann-Realm", "Guild")
    local b = T.newStore("Bob-Realm", "Guild")
    local w = wish(a, 10)
    b:Merge(w)
    local c = assert(b:Claim(w.id, 3))
    a:Merge(b:Get(w.id))
    local before = a:Digest()[w.id]
    assert(b:MarkSent(w.id, c.id))
    assert(a:UpdateWish(w.id, { note = "updated" }))
    a:Merge(b:Get(w.id))
    T.eq(a:Get(w.id).claims[c.id].state, "sent")
    T.check(before ~= a:Digest()[w.id])
    b:Merge(a:Get(w.id))
    T.eq(a:Digest()[w.id], b:Digest()[w.id])
    local stale = { id = w.id, owner = w.owner, name = w.name, qty = w.qty, state = "open", v = 1, created = w.created, modified = w.modified, claims = { [c.id] = { id = c.id, by = c.by, qty = c.qty, state = "cancelled", created = c.created } } }
    a:Merge(stale)
    T.eq(a:Get(w.id).claims[c.id].state, "sent")
    local deleted = assert(a:DeleteWish(w.id))
    b:Merge(deleted)
    b:Merge(stale)
    T.eq(b:Get(w.id).state, "deleted")
end)

T.add("owner store ignores a forged newer body but keeps its claims", function()
    local a = T.newStore("Ann-Realm", "Guild")
    local b = T.newStore("Bob-Realm", "Guild")
    local w = wish(a, 10)
    b:Merge(w)
    local c = assert(b:Claim(w.id, 2))
    local forged = b:Get(w.id)
    forged.v, forged.qty = 99, 1
    a:Merge(forged)
    T.eq(a:Get(w.id).qty, 10, "qty")
    T.eq(a:Get(w.id).v, 1, "v")
    T.check(a:Get(w.id).claims[c.id], "claim missing")
end)

T.add("listeners and invalid claim IDs", function()
    local a = T.newStore("Ann-Realm", "Guild")
    local b = T.newStore("Bob-Realm", "Guild")
    local kinds = {}
    a:OnChange(function(kind) kinds[#kinds + 1] = kind end)
    local w = wish(a)
    b:Merge(w)
    local c = assert(b:Claim(w.id, 1))
    b:Get(w.id).claims["wrong:1"] = { id = "wrong:1", by = "Bob-Realm", qty = 1, state = "open", created = 1000 }
    a:Merge(b:Get(w.id))
    T.eq(a:Get(w.id).claims["wrong:1"], nil)
    b:Get(w.id).claims["wrong:1"] = nil
    assert(b:MarkSent(w.id, c.id))
    a:Merge(b:Get(w.id))
    T.eq(kinds[1], "wish")
    T.eq(kinds[2], "claim_new")
    T.eq(kinds[3], "claim_state")
end)

T.add("claim ranks converge in both directions and wish versions preserve claims", function()
    local a = T.newStore("Ann-Realm", "Guild")
    local b = T.newStore("Bob-Realm", "Guild")
    local c = T.newStore("Cara-Realm", "Guild")
    local w = wish(a, 10)
    b:Merge(w)
    c:Merge(w)
    local bob = assert(b:Claim(w.id, 2))
    local cara = assert(c:Claim(w.id, 3))
    assert(b:MarkSent(w.id, bob.id))
    local cancelled = { id = bob.id, by = bob.by, qty = bob.qty, state = "cancelled", created = bob.created }
    c:Get(w.id).claims[bob.id] = cancelled
    c:Merge(b:Get(w.id))
    T.eq(c:Get(w.id).claims[bob.id].state, "sent")
    cancelled = { id = bob.id, by = bob.by, qty = bob.qty, state = "cancelled", created = bob.created }
    b:Get(w.id).claims[bob.id] = cancelled
    b:Merge(c:Get(w.id))
    T.eq(b:Get(w.id).claims[bob.id].state, "sent")
    a:Merge(b:Get(w.id))
    assert(a:UpdateWish(w.id, { note = "new version" }))
    c:Merge(a:Get(w.id))
    T.check(c:Get(w.id).claims[bob.id] and c:Get(w.id).claims[cara.id])
    a:Merge(c:Get(w.id))
    T.check(a:Get(w.id).claims[bob.id] and a:Get(w.id).claims[cara.id])
    T.eq(a:Digest()[w.id], c:Digest()[w.id])
end)
